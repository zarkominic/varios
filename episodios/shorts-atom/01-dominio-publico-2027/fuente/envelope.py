"""voz-en.wav → env.js: per-frame (24 fps) mouth-open envelope for Atom's lip flap."""
import numpy as np, soundfile as sf
y, sr = sf.read('/home/user/varios/atomo/build/largo/short-dp/voz-en.wav')
if y.ndim > 1: y = y.mean(1)
hop = sr / 24; n = int(len(y) / hop) + 1
e = np.array([np.sqrt(np.mean(y[int(i * hop):int((i + 1) * hop)] ** 2)) if int(i * hop) < len(y) else 0 for i in range(n)])
e = e / np.percentile(e[e > 1e-4], 95); e = np.clip(e, 0, 1); e[e < .08] = 0
open('env.js', 'w').write('// generated by envelope.py from voz-en.wav (24 fps, 0..1)\nexport const ENV = [' + ','.join(f'{v:.2f}' for v in e) + '];\n')
print(n, 'frames')
